    print(f"   Vos Clusters   : {df_eval['predicted_cluster'].nunique()}")
    print(f"    SCORE ARI       : {ari:.4f}")
    print(f"    SCORE V-Measure : {vm:.4f}\n")

    # 4. PRÉPARATION DU TRACÉ
    fig, ax = plt.subplots(1, 2, figsize=(26, 18))
