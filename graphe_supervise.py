        rx, ry = x_ratio * img_w, y_ratio * img_h
        rw, rh = row['w'] * img_w, row['h'] * img_h

        rect = patches.Rectangle((rx, ry), rw, rh, linewidth=3, edgecolor=color, facecolor=color, alpha=0.35)
